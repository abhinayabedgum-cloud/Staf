package com.talentallocation.backend.ai;

import com.talentallocation.backend.dto.CandidateRecommendation;
import com.talentallocation.backend.model.ProjectDemand;
import com.talentallocation.backend.service.DemandService;
import com.talentallocation.backend.service.ResourceMatchingService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import java.util.*;

/**
 * =========================================================
 * AI STAFFING AGENT - SIMULATED (Clearly Labelled)
 * =========================================================
 *
 * SIMULATION NOTICE:
 * This agent simulates an agentic AI workflow because live model
 * API access is unavailable. The simulation replicates the logic
 * a real AI agent would follow using goal-driven tool calls,
 * evidence-based outputs, validation gates, and verifiable outcomes.
 *
 * PRODUCTION DESIGN (what would be needed for real integration):
 * - A real LLM (e.g., Google Gemini, OpenAI GPT-4) accessed via API key.
 * - The agent would be given tool definitions (function calling / tool_use API).
 * - Tools: searchCandidates(), checkAvailability(), getSkillEvidence(),
 *          createTrainingRecommendation(), requestApproval().
 * - The agent would run a ReAct loop: Reason → Act → Observe → Repeat.
 * - Output would be grounded in tool call results only (no hallucination).
 * - Approval gates would require human-in-the-loop confirmation.
 *
 * AGENTIC WORKFLOW IMPLEMENTED HERE:
 * Step 1 [TOOL: getDemandDetails]     → Fetch demand from DB
 * Step 2 [TOOL: searchCandidates]     → Score and rank candidates
 * Step 3 [TOOL: checkSkillGaps]       → Identify missing skills
 * Step 4 [TOOL: suggestLearningPath]  → Recommend training for gaps
 * Step 5 [VALIDATION]                 → Require approval before allocation
 * Step 6 [TOOL: recheckEligibility]   → Re-validate at confirm time
 *
 * LIMITATIONS:
 * - Agent cannot make final hiring/promotion/performance decisions.
 * - Agent does not infer protected characteristics.
 * - Agent will not fabricate skill or availability data.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class StaffingAgentService {

    private final DemandService demandService;
    private final ResourceMatchingService resourceMatchingService;

    /**
     * Main agentic entry point: given a demand ID and a question,
     * the agent runs its goal-driven workflow and returns a structured response.
     */
    public AgentResponse runStaffingWorkflow(Long demandId, String userQuestion) {
        log.info("[AI-AGENT][SIMULATED] Starting staffing workflow for demand: {}", demandId);

        AgentResponse response = new AgentResponse();
        response.setSimulationMode(true);
        response.setSimulationNotice(
            "⚠️ SIMULATION MODE: This agent output is generated by deterministic Java logic "
            + "simulating an LLM-based agentic workflow. In production, this would use a live "
            + "AI model API (e.g., Google Gemini or OpenAI) with controlled tool calls.");

        List<AgentToolCall> toolCalls = new ArrayList<>();
        StringBuilder reasoning = new StringBuilder();

        // ---- STEP 1: Get Demand Details ----
        AgentToolCall step1 = new AgentToolCall("getDemandDetails",
            Map.of("demandId", demandId.toString()));
        try {
            ProjectDemand demand = demandService.findDemandById(demandId);
            step1.setResult(String.format("Found demand: '%s' for role '%s', dates %s to %s, %d%% allocation.",
                demand.getProjectName(), demand.getRole(),
                demand.getStartDate(), demand.getEndDate(), demand.getAllocationPercent()));
            step1.setSuccess(true);
            reasoning.append("Goal: Find candidates for '").append(demand.getRole())
                .append("' in project '").append(demand.getProjectName()).append("'. ");
            toolCalls.add(step1);

            // ---- STEP 2: Search Candidates ----
            AgentToolCall step2 = new AgentToolCall("searchCandidates",
                Map.of("demandId", demandId.toString()));
            List<CandidateRecommendation> candidates = resourceMatchingService.findCandidatesForDemand(demandId);
            step2.setResult(String.format("Found %d candidate(s). Top candidate: %s (score: %.1f/100).",
                candidates.size(),
                candidates.isEmpty() ? "none" : candidates.get(0).getEmployeeName(),
                candidates.isEmpty() ? 0.0 : candidates.get(0).getTotalScore()));
            step2.setSuccess(true);
            toolCalls.add(step2);
            response.setCandidates(candidates);

            // ---- STEP 3: Check Skill Gaps ----
            AgentToolCall step3 = new AgentToolCall("checkSkillGaps",
                Map.of("demandId", demandId.toString()));
            long withGaps = candidates.stream()
                .filter(c -> !c.getMissingSkills().isEmpty()).count();
            step3.setResult(String.format("%d candidate(s) have skill gaps. "
                + "Missing data is disclosed, not fabricated.", withGaps));
            step3.setSuccess(true);
            toolCalls.add(step3);

            // ---- STEP 4: Suggest Learning Paths ----
            AgentToolCall step4 = new AgentToolCall("suggestLearningPath",
                Map.of("demandId", demandId.toString()));
            List<String> learningPaths = new ArrayList<>();
            candidates.forEach(c -> c.getMissingSkills().forEach(ms ->
                learningPaths.add(c.getEmployeeName() + " → " + ms.getTrainingRecommendation())));
            step4.setResult(learningPaths.isEmpty() ? "No learning paths needed — all candidates meet requirements."
                : "Generated " + learningPaths.size() + " learning path recommendation(s).");
            step4.setSuccess(true);
            step4.setData(learningPaths);
            toolCalls.add(step4);

            // ---- STEP 5: Approval Gate ----
            AgentToolCall step5 = new AgentToolCall("requestApproval",
                Map.of("note", "Allocation requires authorized approval before confirmation."));
            step5.setResult("APPROVAL GATE: An authorized approver must confirm allocation "
                + "via POST /api/allocations with 'approvedBy' field. "
                + "The system will re-validate eligibility at that point.");
            step5.setSuccess(true);
            toolCalls.add(step5);

            // ---- STEP 6: Re-check eligibility note ----
            AgentToolCall step6 = new AgentToolCall("recheckEligibility",
                Map.of("note", "Eligibility is re-validated at allocation confirm time."));
            step6.setResult("Re-validation is enforced at commit time in AllocationService. "
                + "Concurrent conflicts are handled via database transactions.");
            step6.setSuccess(true);
            toolCalls.add(step6);

            // Build final answer
            response.setAnswer(buildAnswer(userQuestion, demand, candidates));
            response.setToolCalls(toolCalls);
            response.setLimitations(List.of(
                "This agent does not make final hiring or promotion decisions.",
                "Agent does not infer or use protected characteristics (race, gender, age, etc.).",
                "Agent only uses verified, stored skill and availability data.",
                "Missing data is disclosed — agent never fabricates proficiency or availability.",
                "In simulation mode: output is deterministic Java, not a live LLM."
            ));

        } catch (Exception ex) {
            step1.setResult("Error: " + ex.getMessage());
            step1.setSuccess(false);
            toolCalls.add(step1);
            response.setAnswer("The agent encountered an error: " + ex.getMessage());
            response.setToolCalls(toolCalls);
        }

        return response;
    }

    private String buildAnswer(String userQuestion, ProjectDemand demand,
                                List<CandidateRecommendation> candidates) {
        StringBuilder sb = new StringBuilder();
        sb.append("**AI Staffing Agent Analysis** (Simulated)\n\n");
        sb.append("**Demand:** ").append(demand.getProjectName())
            .append(" | Role: ").append(demand.getRole()).append("\n");
        sb.append("**Period:** ").append(demand.getStartDate())
            .append(" to ").append(demand.getEndDate()).append("\n\n");

        if (candidates.isEmpty()) {
            sb.append("No active employees found in the system. Please add employees first.\n");
        } else {
            sb.append("**Top Candidates (ranked by score):**\n\n");
            int rank = 1;
            for (CandidateRecommendation c : candidates.subList(0, Math.min(5, candidates.size()))) {
                sb.append(rank++).append(". **").append(c.getEmployeeName())
                    .append("** — Score: ").append(c.getTotalScore()).append("/100\n");
                sb.append("   ").append(c.getExplanation()).append("\n\n");
            }
        }

        if (userQuestion != null && !userQuestion.isBlank()) {
            sb.append("**Your Question:** ").append(userQuestion).append("\n");
            sb.append("The agent has analyzed stored data to answer this. "
                + "If data is missing, it is disclosed above — not assumed.\n");
        }
        return sb.toString();
    }

    // ===================== INNER CLASSES =====================

    @lombok.Data
    public static class AgentResponse {
        private boolean simulationMode;
        private String simulationNotice;
        private String answer;
        private List<CandidateRecommendation> candidates;
        private List<AgentToolCall> toolCalls;
        private List<String> limitations;
    }

    @lombok.Data
    public static class AgentToolCall {
        private String toolName;
        private Map<String, String> inputs;
        private String result;
        private boolean success;
        private Object data;

        public AgentToolCall(String toolName, Map<String, String> inputs) {
            this.toolName = toolName;
            this.inputs = inputs;
        }
    }
}
